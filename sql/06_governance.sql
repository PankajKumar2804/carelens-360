/* ============================================================================
   06_governance.sql — tags, masking, row access, audit log
   Policies evaluate at query time under the caller's role, so the agent
   inherits entitlement instead of reimplementing it.
============================================================================ */
USE ROLE CARELENS_ADMIN; USE WAREHOUSE CARELENS_WH; USE DATABASE CARELENS; USE SCHEMA GOVERNANCE;

/* ---- who can see which clinic. entitlement table, not hardcoded roles --- */
