/* ---- masking. IS_ROLE_IN_SESSION so role hierarchies resolve properly --- */
CREATE OR REPLACE MASKING POLICY MP_NAME AS (val STRING) RETURNS STRING ->
  CASE
    WHEN IS_ROLE_IN_SESSION('CARELENS_ADMIN') OR IS_ROLE_IN_SESSION('CARELENS_CLINICIAN') THEN val
    WHEN IS_ROLE_IN_SESSION('CARELENS_CARE_MGR') THEN LEFT(val,1) || '*** ' || SPLIT_PART(val,' ',-1)
    ELSE '***REDACTED***'
  END;

CREATE OR REPLACE MASKING POLICY MP_DOB AS (val DATE) RETURNS DATE ->
  CASE
    WHEN IS_ROLE_IN_SESSION('CARELENS_ADMIN') OR IS_ROLE_IN_SESSION('CARELENS_CLINICIAN') THEN val
    ELSE DATE_FROM_PARTS(YEAR(val), 1, 1)   -- generalise to year of birth
  END;

CREATE OR REPLACE MASKING POLICY MP_POSTAL AS (val STRING) RETURNS STRING ->
  CASE
    WHEN IS_ROLE_IN_SESSION('CARELENS_ADMIN') OR IS_ROLE_IN_SESSION('CARELENS_CLINICIAN') THEN val
    ELSE LEFT(val,3) || 'XX'
  END;

/* free-text clinical narrative is the easiest thing here to re-identify
   someone from, and the analyst role has no need for it */
CREATE OR REPLACE MASKING POLICY MP_CLINICAL_TEXT AS (val STRING) RETURNS STRING ->
  CASE
    WHEN IS_ROLE_IN_SESSION('CARELENS_ADMIN')
      OR IS_ROLE_IN_SESSION('CARELENS_CLINICIAN')
      OR IS_ROLE_IN_SESSION('CARELENS_CARE_MGR') THEN val
    ELSE '***CLINICAL NARRATIVE WITHHELD FOR THIS ROLE***'
  END;

CREATE OR REPLACE ROW ACCESS POLICY RAP_CLINIC_PANEL AS (clinic STRING) RETURNS BOOLEAN ->
  IS_ROLE_IN_SESSION('CARELENS_ADMIN')
  OR IS_ROLE_IN_SESSION('CARELENS_ANALYST')          -- all rows, but masked columns
  OR EXISTS (SELECT 1 FROM CARELENS.GOVERNANCE.CLINIC_ENTITLEMENT e
             WHERE e.attributed_clinic = clinic AND IS_ROLE_IN_SESSION(e.role_name));

