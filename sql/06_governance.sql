/* ---- answer audit trail ------------------------------------------------- */
CREATE OR REPLACE TABLE COPILOT_AUDIT_LOG (
  audit_id STRING DEFAULT UUID_STRING(),
  asked_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  asked_by STRING DEFAULT CURRENT_USER(),
  asked_role STRING DEFAULT CURRENT_ROLE(),
  question STRING, answer STRING,
  tools_used ARRAY, citations ARRAY,
  patient_context STRING, grounded BOOLEAN, latency_ms NUMBER);

CREATE OR REPLACE VIEW V_GROUNDING_SCORECARD AS
SELECT asked_at::DATE AS day, asked_role, COUNT(*) AS answers,
       COUNT_IF(grounded) AS grounded_answers,
       ROUND(100.0 * DIV0(COUNT_IF(grounded), COUNT(*)), 1) AS grounded_pct,
       ROUND(AVG(ARRAY_SIZE(citations)), 2) AS avg_citations_per_answer,
       ROUND(AVG(latency_ms)) AS avg_latency_ms
FROM COPILOT_AUDIT_LOG GROUP BY 1,2 ORDER BY 1 DESC;

